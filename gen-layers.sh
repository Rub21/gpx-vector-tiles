#!/bin/sh
# Writes layers/traces-<name>.sql.jinja2 from traces.sql.jinja2, one per
# layer, with its mode condition on the first line (Tilekiln renders each
# file alone). Run after every change to traces.sql.jinja2.
set -eu
cd "$(dirname "$0")"
mkdir -p layers
# name:condition on mode. Zoom ranges in config.yaml.
for pair in "unknown:mode = 0" "walk:mode = 1" "bike:mode = 2" "vehicle:mode = 3" "plane:mode = 4" "traces:mode <> 4"; do
  name=${pair%%:*}; cond=${pair#*:}
  {
    echo "{# generated by gen-layers.sh from traces.sql.jinja2, do not edit #}"
    echo "{% set mode_sql = \"$cond\" %}"
    cat traces.sql.jinja2
  } > "layers/traces-$name.sql.jinja2"
done
echo "layers written"
