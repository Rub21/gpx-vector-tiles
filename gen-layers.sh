#!/bin/sh
# Writes one Tilekiln layer file per transport mode from traces.sql.jinja2.
# Tilekiln renders each layer file alone (no include, no variables from
# config.yaml), so the mode is set on the first line of each copy.
# Run it after every change to traces.sql.jinja2.
set -eu
cd "$(dirname "$0")"
mkdir -p layers
for pair in unknown:0 walk:1 bike:2 vehicle:3 plane:4; do
  name=${pair%%:*}; mode=${pair##*:}
  {
    echo "{# generated by gen-layers.sh from traces.sql.jinja2, do not edit #}"
    echo "{% set mode = $mode %}"
    cat traces.sql.jinja2
  } > "layers/traces-$name.sql.jinja2"
done
echo "layers written"
